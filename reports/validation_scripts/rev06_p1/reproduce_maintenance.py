"""Reevaluate the same known cases, writing only to the requested output folder.

python reports/validation_scripts/rev06_p1/reproduce_maintenance.py --output /path/to/output
Historical directory names generated by run_revalidation are retained inside
the isolated output; protocol/source hashes identify the maintenance execution.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'src'))
from kgp.experiment import run_full_experiment


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    if output == ROOT or output in (ROOT / 'reports', ROOT / 'configs', ROOT / 'data'):
        parser.error('Choose a separate output directory; audited release artifacts must be preserved.')
    output.mkdir(parents=True, exist_ok=True)
    original = json.loads((ROOT / 'reports/kgp_evaluation_summary.json').read_text(encoding='utf-8'))
    reproduced = run_full_experiment(output / 'reproduction')
    assert set(original['scenarios_detail']) == set(reproduced['scenarios_detail'])
    checks = []
    for sid, scenario in original['scenarios_detail'].items():
        for method, old in scenario['methods'].items():
            new = reproduced['scenarios_detail'][sid]['methods'][method]
            old_metrics, new_metrics = dict(old['metrics']), dict(new['metrics'])
            old_metrics.pop('planning_time_sec', None)
            new_metrics.pop('planning_time_sec', None)
            differences = {key: [old_metrics.get(key), new_metrics.get(key)]
                           for key in old_metrics.keys() | new_metrics.keys()
                           if old_metrics.get(key) != new_metrics.get(key)}
            checks.append({'scenario': sid, 'method': method, 'differences': differences,
                           'feasible': new['feasibility']['is_feasible'],
                           'mandatory_complete': new['feasibility']['mandatory_portfolio_complete']})
    old_hashes = {Path(name).name: value for name, value in original['protocol_config']['input_sha256'].items()}
    new_hashes = {Path(name).name: value for name, value in reproduced['protocol_config']['input_sha256'].items()}
    assert old_hashes == new_hashes and len(new_hashes) == 12
    assert original['paired_eval_comparisons'] == reproduced['paired_eval_comparisons']
    assert len(checks) == 48 and all(not row['differences'] and row['feasible'] and row['mandatory_complete'] for row in checks)
    source_hashes = reproduced['protocol_config']['source_sha256']
    assert all(hashlib.sha256((ROOT / path).read_bytes()).hexdigest() == digest for path, digest in source_hashes.items())
    result = {'release': 'REV06-P1', 'source_commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
              'known_synthetic_plans_reproduced': len(checks), 'frozen_inputs_identical': len(new_hashes),
              'source_hashes_unchanged': len(source_hashes), 'paired_results_identical': True,
              'checks': checks, 'scope': 'Known synthetic reevaluation; no new blind or operational evaluation.'}
    (output / 'comparison.json').write_text(json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False), encoding='utf-8')
    print(json.dumps({key: value for key, value in result.items() if key != 'checks'}, indent=2), flush=True)


if __name__ == '__main__':
    main()
